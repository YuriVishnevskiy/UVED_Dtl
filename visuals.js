function cropView(file, originX, originY, width, zones) {
  const height = width * 2 / 3;
  const points = Object.fromEntries(Object.entries(zones).map(([part, outline]) => [
    part, outline.split(' ').map(pair => {
      const [x, y] = pair.split(',').map(Number);
      return ((x - originX) / width * 100).toFixed(2) + ',' + ((y - originY) / height * 100).toFixed(2);
    }).join(' ')
  ]));
  return {image: 'cars/' + file + '.jpg', aspect: '3/2', zones: points};
}

